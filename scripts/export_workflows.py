"""Export the workflows currently in n8n (including edits made in the UI) to n8n/exported/.

`n8n/workflows/*.json` (generated by n8n/build_workflows.py) is what gets imported on start; use this
export to diff UI changes and port them back into the builder.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "n8n" / "exported"


def run(*args: str) -> None:
    subprocess.run(["docker", "compose", *args], cwd=ROOT, check=True)


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    run("exec", "-T", "n8n", "sh", "-c", "rm -rf /tmp/wf-export && mkdir -p /tmp/wf-export && "
        "n8n export:workflow --all --separate --pretty --output=/tmp/wf-export/")
    run("cp", "n8n:/tmp/wf-export/.", str(OUT))
    print(f"exported to {OUT.relative_to(ROOT)}: {sorted(p.name for p in OUT.glob('*.json'))}")
    sys.exit(0)
